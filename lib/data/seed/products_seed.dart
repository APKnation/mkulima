/// Compact listing builder so the catalogue stays easy to extend.
Product mkP(
  String id,
  String name,
  String cat,
  String sub,
  String subName,
  double price,
  String unit,
  String seller,
  String sellerType,
  String location,
  String region,
  String qty,
  String image, {
  String? desc,
  double? prev,
  bool verified = false,
  bool organic = false,
  bool negotiable = true,
  bool available = true,
  double rating = 4.6,
  int reviews = 0,
  int views = 0,
  int? minOrder,
  String listedAt = 'Leo',
}) {
  return Product(
    id: id,
    name: name,
    categoryId: cat,
    subcategoryId: sub,
    subcategoryName: subName,
    description: desc ??
        '$name bora kutoka kwa $seller, $location. '
            'Bei ni kwa $unit na inaweza kujadiliwa kwa wanunuzi wa kiasi.',
    price: price,
    previousPrice: prev,
    unit: unit,
    location: location,
    region: region,
    sellerName: seller,
    sellerPhone: '+255 7$id'.padRight(14, '0'),
    sellerType: sellerType,
    quantityLabel: qty,
    listedAt: listedAt,
    imageAsset: '$_img/$image',
    rating: rating,
    reviewCount: reviews,
    views: views,
    verified: verified,
    negotiable: negotiable,
    organic: organic,
    available: available,
    minOrder: minOrder,
  );
}

